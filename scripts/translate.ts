// Translate the English UI strings into Indian languages with Amazon Translate and write
// frontend/src/messages/<locale>/index.ts. Run once after `aws configure` (needs translate:TranslateText):
//   npm run translate                    # all locales, only keys that are missing
//   npm run translate -- pa hi           # some
//   npm run translate -- --force ta      # re-translate everything (drops hand edits)
// Existing strings are kept, so hand-fixed translations survive a re-run. {placeholders} and the
// glossary words below are protected with translate="no" spans. Haryanvi (bgc) has no Translate
// support, so new bgc keys are filled from Hindi.
import { TranslateClient, TranslateTextCommand } from '@aws-sdk/client-translate';
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const DIR = join(__dirname, '../frontend/src/messages');
const LOCALES = ['hi', 'pa', 'ta', 'te', 'ml'] as const;
const client = new TranslateClient({ region: process.env.AWS_REGION ?? 'ap-south-1' });

type Tree = { [k: string]: string | Tree };

// Machine translation got "stubble" badly wrong (Tamil "eggs", Punjabi "cold"), so pin the farmers' word.
const STUBBLE: Record<string, string> = { hi: 'पराली', pa: 'ਪਰਾਲੀ', ta: 'வைக்கோல்', te: 'గడ్డి', ml: 'വൈക്കോൽ' };

const protect = (s: string, target: string) =>
  s
    .replace(/\{(\w+)\}/g, '<span translate="no">{$1}</span>')
    .replace(/\bstubble\b/gi, `<span translate="no">${STUBBLE[target] ?? 'stubble'}</span>`);
const unprotect = (s: string) =>
  s
    .replace(/<span translate="no">\s*(.*?)\s*<\/span>/g, '$1')
    .replace(/&amp;/g, '&')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"');

// Brand and units that should stay as written.
const KEEP = new Set(['Parali Setu']);

async function tr(text: string, target: string): Promise<string> {
  if (KEEP.has(text)) return text;
  const { TranslatedText } = await client.send(
    new TranslateTextCommand({ Text: protect(text, target), SourceLanguageCode: 'en', TargetLanguageCode: target }),
  );
  const out = unprotect(TranslatedText ?? text);
  // If a {placeholder} got lost or altered, keep English for this string (t() would break otherwise).
  const vars = (x: string) => (x.match(/\{\w+\}/g) ?? []).sort().join();
  return vars(out) === vars(text) ? out : text;
}

const FORCE = process.argv.includes('--force');

async function walk(node: Tree, target: string, have: Tree = {}): Promise<Tree> {
  const out: Tree = {};
  // Small concurrency to stay under Translate's request rate.
  const entries = Object.entries(node);
  for (let i = 0; i < entries.length; i += 8) {
    await Promise.all(
      entries.slice(i, i + 8).map(async ([k, v]) => {
        const old = have[k];
        if (typeof v !== 'string') out[k] = await walk(v, target, typeof old === 'object' ? old : {});
        else out[k] = typeof old === 'string' && !FORCE ? old : await tr(v, target);
      }),
    );
  }
  return out;
}

const write = (locale: string, msgs: Tree) =>
  writeFileSync(
    join(DIR, locale, 'index.ts'),
    `// Generated by scripts/translate.ts (Amazon Translate${locale === 'bgc' ? ', Hindi used for Haryanvi' : ''}). Hand edits welcome: a re-run keeps them.\nconst messages: Record<string, unknown> = ${JSON.stringify(msgs, null, 2)};\nexport default messages;\n`,
  );

(async () => {
  const en: Tree = {};
  for (const f of readdirSync(join(DIR, 'en')).filter((f) => f.endsWith('.json')))
    en[f.replace('.json', '')] = JSON.parse(readFileSync(join(DIR, 'en', f), 'utf8'));

  const existing = async (locale: string): Promise<Tree> =>
    FORCE ? {} : ((await import(join(DIR, locale, 'index.ts'))).default as Tree);
  // Fill missing keys of `into` from `from` (used to give Haryanvi any new Hindi strings).
  const fill = (into: Tree, from: Tree): Tree =>
    Object.fromEntries(Object.entries(from).map(([k, v]) => [k, typeof v === 'string' ? (typeof into[k] === 'string' ? into[k] : v) : fill((into[k] as Tree) ?? {}, v)]));

  const args = process.argv.slice(2).filter((a) => a !== '--force');
  const wanted = args.length ? args : [...LOCALES];
  for (const locale of wanted) {
    process.stdout.write(`${locale}… `);
    const msgs = await walk(en, locale, await existing(locale));
    write(locale, msgs);
    if (locale === 'hi') write('bgc', fill(await existing('bgc'), msgs));
    console.log('done');
  }
})();
